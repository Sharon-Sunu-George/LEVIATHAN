import sys
import time
import subprocess
from pathlib import Path
import httpx

brain_dir = Path(__file__).resolve().parent
python_exe = brain_dir / ".venv" / "Scripts" / "python.exe"
token_file = brain_dir / ".session_token"

def run_live_verification():
    print("[1] Starting live uvicorn server on 127.0.0.1:8000...")
    # Start server process
    proc = subprocess.Popen(
        [
            str(python_exe),
            "-m",
            "uvicorn",
            "main:app",
            "--host",
            "127.0.0.1",
            "--port",
            "8000",
            "--log-level",
            "warning",
        ],
        cwd=str(brain_dir),
    )

    try:
        # Wait for server to bind
        time.sleep(2)
        base_url = "http://127.0.0.1:8000"

        # Read generated session token
        assert token_file.exists(), "Token file was not generated by server startup"
        token = token_file.read_text(encoding="utf-8").strip()
        assert len(token) > 20, "Session token appears malformed or empty"

        with httpx.Client(base_url=base_url, timeout=5.0) as client:
            # 1. Test missing token
            print("[2] Testing live GET /health without token...")
            res_no_auth = client.get("/health")
            print(f"    Status: {res_no_auth.status_code} (Expected 401)")
            assert res_no_auth.status_code == 401

            # 2. Test invalid token
            print("[3] Testing live GET /health with invalid token...")
            res_bad_auth = client.get(
                "/health", headers={"Authorization": "Bearer bad-token-xyz"}
            )
            print(f"    Status: {res_bad_auth.status_code} (Expected 401)")
            assert res_bad_auth.status_code == 401

            # 3. Test valid token
            print("[4] Testing live GET /health with valid session token...")
            res_valid = client.get(
                "/health", headers={"Authorization": f"Bearer {token}"}
            )
            print(f"    Status: {res_valid.status_code} (Expected 200)")
            print(f"    Response body: {res_valid.json()}")
            assert res_valid.status_code == 200
            assert res_valid.json()["status"] == "ok"

        print("\nLIVE NETWORK VERIFICATION ON 127.0.0.1:8000: ALL PASSED")

    finally:
        print("[5] Terminating test server process...")
        proc.terminate()
        proc.wait(timeout=5)
        print("    Server terminated cleanly.")

if __name__ == "__main__":
    run_live_verification()

